// 시안 15 — 가격 비교표 (PRICE COMPARISON).
//
// 개별 구매 조합 3종과 패스 가격을 한 줄씩 놓고 비교한다. 기존 하반기 멤버십은 탭으로
// 조합을 전환했으나 시안이 단순 목록으로 바뀌어 데이터도 그 형태로 맞춘다.
//
// 금액은 하드코딩이다. 어드민에서 끌어오는 방식(lib/useComparePrices.ts)도 만들었으나
// 되돌렸다 — 조합에 든 챌린지 중 하나라도 모집 중이 아니면 합계를 믿을 수 없어 그 줄이
// 통째로 사라지고, 타입당 1회씩 조회가 붙어 진입 시 여러 번 나갔다. 비교표는 시즌 시작 시
// 정해두고 가는 편이 화면이 안정적이다.
//
// 대신 어드민에서 가격을 바꿔도 여기는 따라가지 않는다. 시즌 중 할인이 바뀌면
// 이 파일을 고쳐 배포해야 한다.
//
// 맨 아래 패스 줄의 금액은 여기 적지 않는다 — 어드민 가격이 이기는 값이라
// `useMembershipChallengeData().salePrice` 를 쓴다. 두 곳에 적으면 어긋난다.

/** 개별 구매 조합 한 줄 */
